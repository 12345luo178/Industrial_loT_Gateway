/**
 * @file    gw_guard.h
 * @brief   内存边界哨兵（金丝雀）检查 —— 测试用工具，不是产品代码
 *
 * ============================================================================
 *  为什么需要它
 *
 *  嵌入式项目里最危险的一类 bug 是**越界写**：
 *
 *      uint8_t buf[8];
 *      buf[8] = 0x5A;          // 越界 1 字节，编译器不管
 *
 *  它不会立刻崩溃，而是悄悄改掉**紧邻的另一个变量**。
 *  症状可能几小时后才出现（那时那个变量才被读到），
 *  现场表现为"偶发异常"、"数据偶尔不对" —— 极难定位。
 *
 *  ----------------------------------------------------------------------------
 *  为什么不用 ASan
 *
 *  本机 MinGW 编译器**没有 sanitizer 运行库**（`-lasan` / `-lubsan` 都不存在），
 *  也没有 clang。在这个环境里 ASan 用不了。
 *
 *  于是自己做"金丝雀"：
 *
 *      [ 前哨 16 字节 ][ 被测缓冲 N 字节 ][ 后哨 16 字节 ]
 *
 *  操作前后各校验一次哨兵。哨兵被改 = 越界了。
 *
 *  这个手段比 ASan 弱（只能查哨兵附近、查不出 use-after-free），
 *  但它恰好覆盖嵌入式里最要命的那一类问题，而且：
 *    - 零依赖，任何编译器都能跑
 *    - 上板也能用（把哨兵放进 RAM，跑一段时间后检查）
 *
 *  ----------------------------------------------------------------------------
 *  ⚠️ 关于"哨兵被改"与"写到了别的变量上"的区别
 *
 *  金丝雀只能证明"越过边界了"，不能直接告诉你是谁越的。
 *  但配合 `gw_guard_dump()` 打印出被改的位置（前哨还是后哨、
 *  偏移多少），通常就能判断方向：
 *
 *      后哨被改且偏移很小  -> 正向越界写（最常见）
 *      前哨被改且偏移很小  -> 负向越界（下标算成了负数）
 *      后哨被改且偏移很大  -> 写飞了（指针错得离谱，通常是野指针）
 * ============================================================================
 */
#ifndef GW_GUARD_H
#define GW_GUARD_H

#include <stdint.h>

/** 哨兵长度（每侧）。16 字节足够发现"越界几个字节"这种最常见的错误。 */
#define GW_GUARD_PAD        16u

/** 前哨填充值 */
#define GW_GUARD_PRE_FILL   0xA5u

/** 后哨填充值 */
#define GW_GUARD_POST_FILL  0x5Au

/**
 * 被测缓冲的最大长度
 *
 * 取 512：够放 Modbus 最大 ADU（256）与串口帧最大总长（133），
 * 也够放寄存器表结构体（96）。
 */
#define GW_GUARD_MAX_DATA   512u

/** 一个受保护的缓冲 */
typedef struct {
    uint8_t  pre[GW_GUARD_PAD];
    uint8_t  data[GW_GUARD_MAX_DATA];
    uint8_t  post[GW_GUARD_PAD];
} gw_guard_t;

/* ==================================================================
 *  接口
 * ================================================================== */

/** 初始化哨兵（填充前后哨，data 清零） */
void gw_guard_init(gw_guard_t *g);

/**
 * 校验哨兵
 *
 * @return 0 = 完好；>0 = 第几个字节被破坏（从头算，1 起）；
 *         <0 = 前哨被破坏
 */
int gw_guard_check(const gw_guard_t *g);

/**
 * 打印被破坏的位置（仅在 check 返回非 0 时有意义）
 *
 * @param label 用于标识是哪个缓冲
 */
void gw_guard_dump(const gw_guard_t *g, const char *label);

/** 取数据区指针 */
uint8_t *gw_guard_data(gw_guard_t *g);

/** 取数据区容量（= GW_GUARD_MAX_DATA，可用长度） */
uint16_t gw_guard_capacity(void);

/* ==================================================================
 *  便捷用法
 *
 *      gw_guard_t g;
 *      gw_guard_init(&g);
 *      gw_frame_feed(&parser, payload, len);
 *      if (gw_guard_check(&g) != 0) { gw_guard_dump(&g, "frame buf"); FAIL; }
 * ================================================================== */

#endif /* GW_GUARD_H */

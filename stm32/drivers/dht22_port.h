/**
 * @file    dht22_port.h
 * @brief   DHT22 单总线温湿度传感器的硬件抽象接口
 *
 * ============================================================================
 *  为什么要把硬件操作抽成函数指针，而不是直接调 HAL？
 *
 *  DHT22 的驱动分两部分：
 *
 *   (1) 纯逻辑（可测）：把传感器输出的 40 bit 解析成温湿度值、校验、滤波、
 *       错误分类。这部分不碰硬件，完全可以在 PC 上单元测试。
 *   (2) 硬件时序（不可测）：拉低总线 18ms 起始信号、按微秒抓取 40 个位的电平。
 *       这部分强依赖 GPIO 与微秒延时，只能在真机上验证。
 *
 *  如果不做这个切分，整个驱动就没法测，只能靠"上板看数值对不对"——
 *  而数值不对时你无法区分是"时序错了"还是"解析错了"。
 *
 *  切分之后，测试可以覆盖：位序、字节序、校验和、负温度、小数点定标、
 *  校验失败、超时、以及"数据线恒低/恒高"这类硬件故障的识别。
 *  真机上只剩"时序准不准"这一件事要确认。
 * ============================================================================
 */
#ifndef DHT22_PORT_H
#define DHT22_PORT_H

#include <stdint.h>

/* ---------------- 硬件操作接口（由具体平台实现） ---------------- */
typedef struct {
    /* 把数据线切为 MCU 输出（用于发起起始信号） */
    void (*set_out)(void *ctx);

    /* 把数据线切为 MCU 输入（带外部上拉，用于读取传感器输出） */
    void (*set_in)(void *ctx);

    /* 输出电平：level 非 0 为高 */
    void (*write)(void *ctx, int level);

    /* 读电平：返回非 0 表示高 */
    int  (*read)(void *ctx);

    /* 微秒级延时。必须精确到 ±10% 以内。
       实现建议：DWT->CYCCNT 计数（见 drivers/dht22_port_stm32.c），
       不要用 HAL_Delay（毫秒级，精度完全不够）。 */
    void (*delay_us)(void *ctx, uint32_t us);

    /* 微秒级时间戳，单调递增。
       驱动用它配合 read() 做轮询式计时，例如：
         t0 = now_us(); while (read() == 1 && now_us()-t0 < to) {} dur = now_us()-t0;
       这是单总线驱动最经典也最容易验证的写法 ——
       不需要额外的"等待回调"，计时语义完全由 now_us 决定。 */
    uint32_t (*now_us)(void *ctx);

    void *ctx;              /* 传给上面各函数的上下文（通常是 GPIO 端口/引脚封装） */

    /* ---------------- 临界区（**可选**，2026-10-13 加，缺陷 AF） ----------------
     *
     * 为什么需要：单总线的**响应窗口**（释放总线 -> 收完 40 bit，约 4.2ms）
     * 完全由传感器驱动时序，主机只做被动测量。在 FreeRTOS 下只要这段时间
     * 被更高优先级任务抢占一次（>4.2ms），整帧就过去了，等任务回来只会看到
     * 一条静止的高电平 -> 被如实报成 `DHT22_ERR_STUCK_HIGH`，
     * 与"传感器没接"**症状完全一样**，极难区分（板上实测踩过）。
     *
     * 所以这两个回调由移植层实现，驱动在**响应窗口**前后成对调用。
     *
     * ⚠️ 语义要求：enter 之后到 exit 之前，**不允许任何其它执行流**
     *    （任务切换、中断）插进来。FreeRTOS 下用 `taskENTER_CRITICAL()`，
     *    裸机下用 `__disable_irq()`。
     *
     * ⚠️ 两个都为 NULL 时驱动退化为"无保护"（PC 单元测试就是这种情形）——
     *    这是刻意保留的：本文件（纯逻辑）必须能在没有 RTOS 的主机上测。
     *
     * ⚠️ **必须成对调用**：驱动已把带多个 return 的解析过程单独拆成
     *    一个函数，就是为了保证配对（见 drivers/dht22.c 的说明）。
     *    实现方不要在其中做耗时操作 —— 它直接决定关中断时长。 */
    void (*enter_critical)(void *ctx);
    void (*exit_critical)(void *ctx);
} dht22_hw_t;

/* ---------------- 错误码 ---------------- */
typedef enum {
    DHT22_OK               = 0,
    DHT22_ERR_NO_RESPONSE  = -1,   /* 传感器无响应（起始信号后未拉低） */
    DHT22_ERR_TIMEOUT      = -2,   /* 等待电平跳变超时 */
    DHT22_ERR_CHECKSUM     = -3,   /* 40 bit 校验和不匹配 */
    DHT22_ERR_PARAM        = -4,   /* 入参非法（如 hw 回调缺失） */
    DHT22_ERR_STUCK_LOW    = -5,   /* 数据线恒低：短路或传感器损坏 */
    DHT22_ERR_STUCK_HIGH   = -6    /* 数据线恒高：未接或上拉但无器件 */
} dht22_err_t;

/* ---------------- 原始数据结构（解析后的物理量） ---------------- */
typedef struct {
    int16_t  temp_x10;      /* 温度 ×10，例 253 = 25.3℃；负值如 -105 = -10.5℃ */
    uint16_t humi_x10;      /* 湿度 ×10，例 612 = 61.2%RH */
    uint8_t  raw[5];        /* 原始 5 字节，便于现场排障时核对 */
    uint8_t  checksum_ok;   /* 1 = 校验通过 */
} dht22_raw_t;

/* ---------------- 滤波后的数据 ---------------- */
/* 滑动均值滤波窗口大小。设计文档取 N=5。
   放在结构体里而不是文件级静态数组，原因：
     1) 无隐藏状态，多个实例互不干扰（也才能写单元测试）
     2) 换传感器/换实例不需要清理全局变量
   代价：每个实例多占 5×4 + 5×4 = 40 字节 RAM，可以接受。 */
#define DHT22_FILTER_WINDOW   5u

typedef struct {
    int16_t  temp_x10;      /* 滑动均值滤波后的温度 */
    uint16_t humi_x10;      /* 滑动均值滤波后的湿度 */
    uint8_t  valid;         /* 1 = 至少有一次有效采样，值可用 */
    uint8_t  fail_streak;   /* 连续失败次数（用于上报设备状态） */
    uint32_t stat_reads;    /* 累计读取尝试次数 */
    uint32_t stat_ok;       /* 累计校验成功次数 */
    uint32_t stat_err_crc;  /* 累计校验失败次数 */
    uint32_t stat_err_to;   /* 累计超时次数 */

    /* 内部状态：滑动窗口（调用方不要直接改） */
    int32_t  win_temp[DHT22_FILTER_WINDOW];
    uint32_t win_humi[DHT22_FILTER_WINDOW];
    uint8_t  win_count;
    uint8_t  win_idx;
} dht22_filtered_t;

/* ==========================================================================
 *  纯逻辑部分：可在 PC 上单元测试
 * ========================================================================== */

/**
 * 把传感器输出的 5 字节解析为温湿度值
 *
 * 数据格式（DHT22 手册）：
 *   byte0 = 湿度高 8 位
 *   byte1 = 湿度低 8 位
 *   byte2 = 温度高 8 位（bit7 为符号位：1 表示负温度）
 *   byte3 = 温度低 8 位
 *   byte4 = 校验和 = (byte0+byte1+byte2+byte3) & 0xFF
 *
 * 温度定标：原始值 253 表示 25.3℃（即 ×10）。
 * 负温度：若 byte2 的 bit7 为 1，真实温度 = -(原始值 & 0x7FFF) / 10。
 *
 * @return DHT22_OK，或 DHT22_ERR_CHECKSUM
 */
dht22_err_t dht22_decode(const uint8_t raw[5], dht22_raw_t *out);

/**
 * 把一串"高电平持续微秒数"（40 个）解码为 5 字节
 *
 * 工作原理：DHT22 用"高电平持续时间"区分 0 和 1：
 *   高电平约 26~28 µs → 位 0
 *   高电平约 70 µs    → 位 1
 * 判据取 50 µs 作为阈值（0 与 1 的中间值，留足噪声余量）。
 *
 * 单独抽出来的价值：真机抓到的时序数组可以直接喂给这个函数，
 * 在 PC 上验证位解码是否正确 —— 把"时序采集"与"位判定"解耦。
 *
 * @param highs_us  40 个高电平持续时长（微秒）
 * @param out       输出 5 字节
 * @return DHT22_OK
 */
dht22_err_t dht22_bits_to_bytes(const uint16_t highs_us[40], uint8_t out[5]);

/**
 * 滑动均值滤波：把一次采样并入滤波器
 *
 * 设计取舍：
 *   - 采用"定长环形缓冲 + 求和"而不是"递推平均"，
 *     因为窗口仅 5，求和只需 5 次加法，比维护浮点递推更简单且无累积误差。
 *   - 失败采样不写入缓冲区（否则错误值会污染均值）。
 *   - 只有全部窗口填满后才输出有效值？不：只要有 1 个有效值就输出，
 *     这样刚上电也能立即有读数，随着采样增多逐步平滑。
 *
 * @param f        滤波器状态（调用方分配，首次使用前需 dht22_filter_init）
 * @param window   窗口大小（建议 5）
 * @param sample   本次采样结果；为 NULL 表示本次采样失败
 */
void dht22_filter_init(dht22_filtered_t *f);
void dht22_filter_push(dht22_filtered_t *f, const dht22_raw_t *sample);

/**
 * 把一次读取失败按类别记入统计
 *
 * 为什么单独一个函数：dht22_read() 内部每次失败都要记，
 * 但如果驱动自己内部维护统计，就会重新引入"隐藏状态"。
 * 所以由调用方把过滤器传进来，失败时由驱动回填统计。
 *
 * @param f    滤波器状态（可为 NULL，此时什么都不做）
 * @param err  本次失败的错误码
 */
void dht22_filter_note_error(dht22_filtered_t *f, dht22_err_t err);

/* ==========================================================================
 *  硬件部分：需要在真机上运行
 * ========================================================================== */

/**
 * 读取一次 DHT22（含校验重读）
 *
 * 流程：发起起始信号 → 等响应 → 抓 40 个位 → 解析 → 校验
 *       校验失败则重试，最多 retry 次。
 *
 * @param hw     硬件操作接口
 * @param out    解析结果输出
 * @param retry  校验失败时的重试次数（0 表示不重试）
 * @param f      滤波器状态，用于回填失败分类统计；可为 NULL
 * @return DHT22_OK 或最后一次的错误码
 */
dht22_err_t dht22_read(const dht22_hw_t *hw, dht22_raw_t *out, uint8_t retry,
                       dht22_filtered_t *f);

/**
 * 读取并滤波（应用层最常用的入口）
 *
 * 内部依次完成：dht22_read() -> dht22_filter_push()
 * 失败时也会 push 一次（只累加 fail_streak，不污染均值），
 * 这样上层只要调这一个函数，就能同时拿到原始值、滤波值和统计。
 *
 * @param hw     硬件操作接口
 * @param f      滤波器状态
 * @param retry  校验失败时的重试次数
 * @return DHT22_OK 或错误码；无论成败，f 里的统计都已更新
 */
dht22_err_t dht22_read_and_filter(const dht22_hw_t *hw,
                                  dht22_filtered_t *f,
                                  uint8_t retry);

/** 错误码转可读字符串（日志用） */
const char *dht22_strerror(dht22_err_t err);

#endif /* DHT22_PORT_H */

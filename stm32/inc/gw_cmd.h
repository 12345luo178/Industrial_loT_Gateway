/**
 * @file    gw_cmd.h
 * @brief   下行指令解释（纯逻辑，可在 PC 上单元测试）
 *
 * ============================================================================
 *  这条链路解决什么问题
 *
 *  本项目的数据流本来是单向的：采集 -> 上云。但有几种操作**必须能远程做**：
 *
 *    - 现场安装完了想确认"到底通没通" -> 立即上报一次
 *    - 参数改错了想恢复出厂          -> 恢复默认
 *    - 排查完想清掉告警状态位        -> 清 sticky
 *    - 固件升级完想让它生效          -> 重启
 *
 *  没有这条链路，每次都得人到现场接调试器 —— 这是"有没有产品化"的分界线。
 *
 *  ----------------------------------------------------------------------------
 *  三个设计决定
 *
 *  **① 用文本协议而不是二进制**
 *
 *      文本：`period 30`、`save`
 *      二进制：`[0x03][0x00][0x1E]`
 *
 *  看起来二进制更省，但代价是：不可读、不可手打、每条指令都要查文档。
 *  ESP32 侧是 Python/MicroPython 环境，拼个字符串一分钟的事；
 *  而**现场调试时能直接用 MQTT 客户端手打一条指令**的价值非常大。
 *
 *  代价是解析开销：最长 128 字节的字符串解析在 72MHz 上约几微秒
 *  （见 `test/bench.c` 的基准），相比它带来的可运维性完全值得。
 *
 *  **② ⚠️ 危险指令必须带确认令牌**
 *
 *      `restore` / `reboot` / `save` 这三条会改变设备状态，
 *      其中 `restore` 会**清掉现场标定的参数**。
 *
 *      如果只认 `"restore"` 这个词，那么任何一条误发的消息
 *      （例如有人在 MQTT 主题上发了句英文、或者上位机脚本有 bug）
 *      都可能把一台装在高处的设备恢复出厂。
 *
 *      所以要求写成 `restore 0x5A5A` 这种形式 —— 令牌就是寄存器表里
 *      那两个命令字的值（`HREG_PARAM_DFLT_CMD`）。
 *      这样"误发"几乎不可能命中，而**故意操作也只是多打几个字符**。
 *
 *      这不是过度设计：现场设备一旦装上去，去一次的成本可能是几小时。
 *
 *  **③ 解析与执行分离**
 *
 *      `gw_cmd_parse()` 只把字符串变成结构体，**不产生任何副作用**；
 *      `gw_cmd_apply()` 才真正改状态。
 *
 *      分开的好处是解析逻辑可以 100% 单测覆盖（各种畸形输入），
 *      而执行部分只需要测"每条动作做对了没有"。
 *      如果混在一起，测畸形输入就得准备一堆设备状态。
 *
 *  ----------------------------------------------------------------------------
 *  格式约定
 *
 *      指令 [参数] [参数] ...
 *
 *  用空格或制表符分隔，**大小写不敏感**（现场手打时大小写很难保证），
 *  允许前后有空白。空行会被忽略而不是报错（MQTT 上偶尔会有空消息）。
 * ============================================================================
 */
#ifndef GW_CMD_H
#define GW_CMD_H

#include <stdint.h>

/* ==================================================================
 *  指令类型
 * ================================================================== */
typedef enum {
    GW_CMD_NONE = 0,        /* 空指令（空行/纯空白）：静默忽略，不报错 */
    GW_CMD_REPORT_NOW,      /* 立即上报一次遥测 */
    GW_CMD_SET_PERIOD,      /* 设置上报周期，参数：秒（1~3600） */
    GW_CMD_SAVE,            /* 保存参数到 Flash（需确认令牌） */
    GW_CMD_RESTORE,         /* 恢复出厂参数（需确认令牌） */
    GW_CMD_REBOOT,          /* 重启设备（需确认令牌） */
    GW_CMD_CLEAR_STICKY,    /* 清粘滞状态位，参数：位掩码（十六进制或十进制） */
    GW_CMD_GET_STATUS,      /* 请求上报一次状态（走 ACK 载荷） */
    GW_CMD_SET_UPLINK,      /* 开/关上云，参数：on|off */
    GW_CMD_UNKNOWN          /* 无法识别的指令 */
} gw_cmd_id_t;

/* ==================================================================
 *  结果码（用于回给 ESP32 的 ACK/NACK）
 *
 *  ⚠️ 数值是**跨设备契约**（ESP32 侧要按它判断）。改动要同步 ESP32。
 * ================================================================== */
typedef enum {
    GW_CMD_OK            = 0,   /* 执行成功 */
    GW_CMD_ERR_SYNTAX    = 1,   /* 语法错误（参数缺失/无法解析） */
    GW_CMD_ERR_RANGE     = 2,   /* 参数越界（例如周期 0 或 99999） */
    GW_CMD_ERR_UNKNOWN   = 3,   /* 未知指令 */
    GW_CMD_ERR_TOKEN     = 4,   /* 缺少或错误的确认令牌 */
    GW_CMD_ERR_STATE     = 5,   /* 当前状态不允许（例如上云就是关的） */
    GW_CMD_ERR_INTERNAL  = 6    /* 内部错误（Flash 写失败等） */
} gw_cmd_result_t;

/* ==================================================================
 *  解析结果
 * ================================================================== */
typedef struct {
    gw_cmd_id_t id;

    /* 通用参数（含义随 id 变化） */
    uint32_t    arg0;       /* SET_PERIOD: 秒；CLEAR_STICKY: 位掩码 */
    uint32_t    token;      /* 危险指令的确认令牌 */
    uint8_t     flag;       /* SET_UPLINK: 1 = on, 0 = off */

    /* 诊断：解析到第几个字符出错（便于现场定位） */
    uint16_t    err_pos;
} gw_cmd_t;

/* 文本指令的最大长度（与帧载荷上限一致） */
#define GW_CMD_MAX_LEN      128u

/* 确认令牌：与寄存器 HREG_PARAM_DFLT_CMD 保持一致（0xA5A5） */
#define GW_CMD_TOKEN_SAVE       0x5A5Au
#define GW_CMD_TOKEN_RESTORE    0xA5A5u
#define GW_CMD_TOKEN_REBOOT     0x1234u

/* ---------------- 参数范围 ---------------- */
#define GW_CMD_PERIOD_MIN       1u
#define GW_CMD_PERIOD_MAX       3600u

/* ==================================================================
 *  接口
 * ================================================================== */

/**
 * 解析一条指令
 *
 * @param text 文本（**不必以 '\0' 结尾** —— 用 len 界定）
 * @param len  长度
 * @param out  输出
 * @return GW_CMD_OK 解析成功（含 GW_CMD_NONE / GW_CMD_UNKNOWN）；
 *         其他值为错误码（见 gw_cmd_result_t）
 *
 * @note 本函数**无副作用**，可以随便用畸形输入调用。
 *       它也不修改 text（const）。
 */
gw_cmd_result_t gw_cmd_parse(const char *text, uint16_t len, gw_cmd_t *out);

/**
 * 判断一条指令是否需要确认令牌
 * @return 1 需要；0 不需要
 *
 * 导出这个函数是为了让上层在解析后能统一检查，
 * 也为了测试能验证"危险指令清单"没有漏掉新的指令。
 */
int gw_cmd_needs_token(gw_cmd_id_t id);

/** 取该指令期望的令牌值（不需要令牌时返回 0） */
uint32_t gw_cmd_expected_token(gw_cmd_id_t id);

/** 校验令牌 */
gw_cmd_result_t gw_cmd_check_token(const gw_cmd_t *cmd);

/** 指令名（日志与响应里回显用） */
const char *gw_cmd_id_str(gw_cmd_id_t id);

/** 结果码字符串 */
const char *gw_cmd_result_str(gw_cmd_result_t r);

/**
 * 生成一条指令的"用法说明"（用于 NACK 时告诉对方怎么用）
 *
 * @param id  指令
 * @param out 输出缓冲
 * @param cap 缓冲容量
 * @return 写入的字符数（不含 '\0'）；0 表示没有用法说明
 *
 * ⚠️ 为什么要把用法说明回给上位机：
 *    现场手打指令时打错是常态。如果只回一个"SYNTAX_ERROR"，
 *    操作员还得去翻文档；回一句 `usage: period <1..3600>`
 *    就能自己改对。**这是把文档放进协议里**。
 */
uint16_t gw_cmd_usage(gw_cmd_id_t id, char *out, uint16_t cap);

#endif /* GW_CMD_H */

/**
 * @file    gw_sched.h
 * @brief   任务划分与协作式调度（纯逻辑，可在 PC 上单元测试）
 *
 * ============================================================================
 *  这个模块解决什么问题
 *
 *  裸机版的 `gw_app_poll()` 是一个大函数，里面按固定顺序做完所有事。
 *  上 FreeRTOS 时要把它拆成任务，但**拆法有好有坏**：
 *
 *    差的拆法：想起来一个功能就建一个任务
 *      -> 任务数量失控、优先级靠猜、栈大小靠估、共享状态到处加锁
 *
 *    好的拆法：先想清楚"哪些事有独立的时序要求"，再按它划分
 *      -> 任务数量由时序需求决定，而不是由功能列表决定
 *
 *  ----------------------------------------------------------------------------
 *  本项目的任务划分依据：**时序要求 + 阻塞特性**
 *
 *    任务              周期      硬超时?  阻塞特性
 *    --------------    --------  --------  --------------------------
 *    RS485 从站        每轮       **有**    串口收发（发送是阻塞的）
 *    Modbus 主站       每轮       无        状态机 + 串口（可等）
 *    传感器采样        2.5s       无        **关中断 ~5ms**（单总线时序）
 *    CAN               每轮       无        纯内存 + 状态机
 *    上云               每轮       无        串口（可能阻塞 12ms）
 *    汇聚与看护         每轮      ——        喂狗必须在这里
 *
 *  三条划分原则：
 *
 *  **① 有硬超时的独立成任务，且优先级最高。**
 *     RS485 从站要应答上位机，上位机等几十到几百毫秒就判离线。
 *     它必须能抢占其他一切事情 —— 包括正在关中断的传感器采样之外的部分。
 *
 *  **② 会长时间关中断的必须单独成任务。**
 *     DHT22 单总线时序要求关中断约 5ms。如果它和别的活塞在一个任务里，
 *     那 5ms 会连带阻塞同任务内的其他工作。
 *     独立成任务之后，"关中断"的影响范围就被限制在它自己身上。
 *
 *  **③ 喂狗必须放在"所有任务都得让路"的地方。**
 *     这是本模块最重要的设计点，详见 gw_sched_watchdog_ok() 的说明。
 *
 *  ----------------------------------------------------------------------------
 *  为什么本模块能直接跑在裸机上
 *
 *  它实现的是一个**协作式轮询调度器**：每个任务在 `gw_sched_run()` 里
 *  按优先级顺序被调用一次，各自用非阻塞状态机推进。
 *  这与超级循环是同一个模型，所以：
 *
 *    - 裸机阶段可以直接用（就是现有超级循环的结构化版本）
 *    - 上 FreeRTOS 时，每个任务对应一个 `xTaskCreate`，
 *      任务体直接调用同一个 `entry()` 函数 —— **业务代码零改动**
 *
 *  这样"任务化"这件事在 PC 上就能被完整测试，
 *  而不是等到上了 RTOS 才发现划分有问题。
 * ============================================================================
 */
#ifndef GW_SCHED_H
#define GW_SCHED_H

#include <stdint.h>

/* ---------------- 任务 ID ----------------
 *
 * 顺序即**优先级顺序**（数值越小优先级越高），
 * 也是 `gw_sched_run()` 里的调用顺序。
 */
typedef enum {
    GW_TASK_SLAVE   = 0,    /* RS485 从站：应答上位机（硬超时） */
    GW_TASK_MASTER  = 1,    /* Modbus 主站轮询（可等） */
    GW_TASK_CAN     = 2,    /* CAN 收发 + Bus-Off 恢复 */
    GW_TASK_UPLINK  = 3,    /* 上云链路（帧解析 + 补传 + 心跳） */
    GW_TASK_SENSOR  = 4,    /* DHT22 采样（关中断 ~5ms，周期 2.5s） */
    GW_TASK_HOUSE   = 5,    /* 汇聚、看护、喂狗 */
    GW_TASK_UI      = 6,    /* 本地界面（手绘 4 页）。
                             * ⚠️ 为什么可以排在 HOUSE 之后：
                             *   "HOUSE 必须最后"是**裸机顺序调度**的约束
                             *   （gw_sched_run 跑完后才喂狗）；RTOS 下由
                             *   优先级决定顺序，HOUSE 与 UI 同为最低优先级 1。
                             *   裸机路径不给 UI 配任务 -> 它的 state 保持 IDLE
                             *   -> 看门狗判据会跳过它，不会误判"任务卡死"。 */
    GW_TASK_COUNT   = 7
} gw_task_id_t;

/* ---------------- 任务状态 ---------------- */
typedef enum {
    GW_TASK_ST_IDLE    = 0, /* 未启动 */
    GW_TASK_ST_READY   = 1, /* 已启动，等待被调度 */
    GW_TASK_ST_RUNNING = 2, /* 正在执行 */
    GW_TASK_ST_SUSPEND = 3, /* 被挂起（例如安全模式下禁用了某个任务） */
    GW_TASK_ST_FAULT   = 4  /* 出过错（entry 返回负值） */
} gw_task_state_t;

/* ---------------- 单任务统计 ---------------- */
typedef struct {
    uint32_t runs;              /* 被调度的次数 */
    uint32_t total_us;          /* 累计耗时 */
    uint32_t max_us;            /* 最大单次耗时（**决定优先级的关键**） */
    uint32_t min_us;
    uint32_t over_budget;       /* 超过时间片的次数 */
    uint32_t deadline_miss;     /* 超过硬超时的次数（仅对有硬超时的任务有意义） */
} gw_task_stat_t;

/* ---------------- 任务定义 ---------------- */
typedef struct {
    const char *name;

    /**
     * 任务体
     *
     * @param ctx 上下文（通常是 gw_app_t*）
     *
     * ⚠️ 签名刻意与 FreeRTOS 的 `TaskFunction_t`（`void (*)(void *)`）
     *    **完全一致**。这样上 RTOS 时任务体可以原样复用：
     *
     *        xTaskCreate(gw_app_task_entry_slave, "slave", 256, app, 5, NULL);
     *
     *    如果这里写成 `int (*)(void *)`（用返回值表达"是否做了事"），
     *    任务体就得为裸机与 RTOS 各写一份，或者到处强转函数指针 ——
     *    后者是未定义行为。**签名一致的价值远大于多一个统计字段。**
     *
     * **约定**：entry 必须是非阻塞的 —— 它只推进状态机的一小步。
     * 这一点在裸机与 RTOS 下都成立：裸机下阻塞会拖慢其他任务，
     * RTOS 下阻塞会占满整个时间片（而其他任务未必能让路给真正急的）。
     */
    void (*entry)(void *ctx);

    uint16_t period_ms;         /* 期望周期；0 = 每轮都跑 */
    uint16_t budget_us;         /* 期望的最大耗时（时间片预算） */
    uint16_t deadline_us;       /* 硬超时（0 = 无硬超时要求） */
} gw_task_def_t;

/* ---------------- 调度器上下文 ---------------- */
typedef struct {
    gw_task_def_t   tasks[GW_TASK_COUNT];
    gw_task_stat_t  stat[GW_TASK_COUNT];
    gw_task_state_t state[GW_TASK_COUNT];

    uint32_t due_ms[GW_TASK_COUNT];     /* 距下次该跑还有多少毫秒 */

    /**
     * 看门狗"喂狗许可"计数
     *
     * 每次有任务跑过就 +1。喂狗时调用 gw_sched_watchdog_ok() 检查，
     * 它会把这计数清零 —— 于是"上一轮有没有任务跑过"就成了喂狗的前提。
     * 详见 gw_sched_watchdog_ok() 的说明。
     */
    uint32_t progress;

    /**
     * ---- 心跳判据（★ RTOS 下用；2026-10-11 加）----
     *
     * ⚠️⚠️ 为什么必须有它（缺陷 U）：
     *    RTOS 下每个任务自己 `for(;;)` 循环，**`gw_sched_run()` 根本不被调用**，
     *    所以 `progress` 永远是 0 —— 而"任意任务跑过就算有进展"这种全局判据
     *    也无法回答"**某个**任务单独死掉了"（其余任务照跑，progress 照涨）。
     *
     *    所以 RTOS 下改用**按任务的心跳 + 截止时间**：
     *    每个任务每跑一轮调 `gw_sched_note_beat()` 登记一次；
     *    喂狗时要求**每个已启动且未挂起的任务**都在
     *    `period_ms + GW_SCHED_WD_SLACK_MS` 之内登记过。
     *
     *    ⚠️ 没接毫秒时间源时（裸机构建）自动退回 `progress` 判据，
     *       行为与以前**完全一致**。
     */
    uint32_t (*now_ms)(void *ctx);          /* 毫秒时间源；NULL = 用 progress 判据 */
    void     *now_ms_ctx;

    uint32_t last_beat_ms[GW_TASK_COUNT];   /* 各任务最近一次心跳时刻 */
    uint8_t  beat_seen[GW_TASK_COUNT];      /* 是否登记过心跳 */
    uint32_t wd_ref_ms;                     /* 还没登记过心跳时的计时基准 */

    uint32_t loops;                     /* 调度轮数 */

    /* 时间源（可选；NULL 则不做耗时统计） */
    uint32_t (*now_us)(void *ctx);
    void     *time_ctx;

    uint8_t  inited;
} gw_sched_t;

/* ==================================================================
 *  接口
 * ================================================================== */

/**
 * 初始化调度器
 *
 * @param s        上下文
 * @param defs     任务定义数组（长度必须为 GW_TASK_COUNT，顺序即优先级）
 * @param now_us   微秒时间源（可为 NULL = 不做耗时统计）
 * @param time_ctx 时间源上下文
 */
int gw_sched_init(gw_sched_t *s, const gw_task_def_t *defs,
                  uint32_t (*now_us)(void *ctx), void *time_ctx);

/**
 * 启动所有任务（把状态从 IDLE 置为 READY，并让到期任务立即执行一次）
 */
void gw_sched_start(gw_sched_t *s);

/**
 * 运行一轮调度
 *
 * @param s          上下文
 * @param ctx        传给各任务 entry 的上下文
 * @param elapsed_ms 距上次调用经过的毫秒数
 * @return 本轮实际执行的任务数
 *
 * 行为：
 *   1) 按优先级顺序（数组顺序）遍历任务
 *   2) 只执行"到期"的任务（period_ms 累减到 0）
 *   3) 每个任务只调用**一次** entry（非阻塞约定）
 *   4) 记录耗时、判断是否超预算/超硬超时
 *   5) 更新看门狗 progress 计数
 */
uint8_t gw_sched_run(gw_sched_t *s, void *ctx, uint32_t elapsed_ms);

/**
 * ⚠️ 看门狗喂狗前的检查 —— 本模块最重要的一个接口
 *
 * @return 1 = 允许喂狗；0 = **不允许**（说明有任务被卡住了）
 *
 * ============================================================================
 *  为什么喂狗不能简单地"主循环里调一次"
 *
 *  裸机下常见写法是：
 *
 *      while (1) {
 *          do_something();
 *          HAL_IWDG_Refresh(&hiwdg);      // ❌ 这样喂狗等于没开狗
 *      }
 *
 *  问题是：如果 `do_something()` 内部卡住了（死循环、等一个永远不来的标志），
 *  这行喂狗**也一起卡住了**，看门狗确实会复位 —— 这看起来是对的。
 *
 *  但真正的坑在于**任务化之后**：一旦某个任务被单独拆出去，
 *  主循环可能还在正常跑（于是继续喂狗），而那个任务已经死了。
 *  看门狗永远不会触发，设备"看起来在运行"但功能已经废了。
 *
 *  ============================================================================
 *  ⚠️⚠️ 本函数有**两套判据**，用哪套取决于有没有接毫秒时间源
 *  （2026-10-11 修正：原来只有一套，而文档把它说成了另一套 —— 缺陷 U）
 *  ============================================================================
 *
 *  【判据一】心跳判据（★ RTOS 用；接了 `gw_sched_set_clock_ms()` 时）
 *
 *      每个**已启动且未挂起**的任务，都必须在
 *      `period_ms + GW_SCHED_WD_SLACK_MS` 之内登记过一次心跳
 *      （`gw_sched_note_beat()`，由 RTOS 的任务体每轮调用）。
 *
 *      => **任一任务卡死**（不再登记心跳）-> 超过它的周期 + 余量后
 *         喂狗被拒 -> IWDG 复位。**这也是文档一直声称的语义。**
 *
 *      ⚠️ 检测延迟 = 该任务的 `period + SLACK`（慢周期任务会更久）。
 *         慢任务死掉时，喂狗会先停下来，但要等它自己的截止时间过去，
 *         所以别指望"1.6 秒内一定复位"。
 *
 *  【判据二】进展判据（裸机用；没接时间源时，行为与以前**完全一致**）
 *
 *      每次 `gw_sched_run()` 里每个执行过的任务都会让 `progress` +1；
 *      喂狗时检查"自上次喂狗以来 progress 是否增长过"，并**消费掉**该计数。
 *
 *      ⚠️ 它的真实语义是"**完全停摆**才拒喂"：
 *         5 个任务照跑、1 个任务死了，progress 照样增长 -> **仍然会喂**。
 *         （裸机下这个洞被另一个机制盖住了：任务体在 `gw_sched_run()` 里
 *           **顺序执行**，某个任务死循环会让整个 `gw_sched_run()` 不返回，
 *           主循环根本走不到喂狗那一行 -> 狗照样会叫。）
 *
 *  ============================================================================
 *  RTOS 下"任务占着 CPU 不放"这一类，由**空闲任务钩子**兜住：
 *  空闲任务只在所有任务都阻塞时才被调度到，所以"任务死循环"会让
 *  钩子根本不执行 -> 连判据一都不需要就停喂了。
 *  判据一专门补的是另一类：**任务阻塞在等一个永远不来的东西**
 *  （CPU 空着、空闲钩子在跑，但那个任务再也不前进了）。
 * ============================================================================
 */
int gw_sched_watchdog_ok(gw_sched_t *s);

/**
 * ★ 允许一个任务比它的周期多"迟到"多久，才判定它死了
 *
 * 判据是 `now - 最近一次心跳 > period_ms + GW_SCHED_WD_SLACK_MS`。
 * 留这个余量的理由：任务周期是**期望值**，实际会因为抢占、长阻塞路径
 * （Flash 擦除 1.4~2.7 秒、DHT22 关中断 5 毫秒）而抖动。
 *
 * ⚠️ 取值的两个约束：
 *   · 太小 -> 正常抖动被当成"任务死了" -> **误复位**
 *   · 太大 -> 任务真死了也要很久才复位（检测延迟 = period + SLACK）
 *   1000 ms 是折中：比 IWDG 超时（2.13~4.27 秒）小一档，
 *   而调度抖动量级是"毫秒"，所以不会误判。
 *
 * ⚠️ 注意 **检测延迟与 IWDG 超时是两件事**：
 *   某个慢周期任务（例如 10 秒周期）死掉时，喂狗会先停下来，
 *   但要等到 `10 秒 + 1 秒` 才停喂 —— 所以真正的复位时刻是
 *   `period + SLACK + IWDG 超时`。这一点必须如实写在文档里，
 *   不能笼统说"任一任务卡死 3.2 秒内复位"。
 */
#define GW_SCHED_WD_SLACK_MS   1000u

/**
 * ★ 接上毫秒时间源（RTOS 下由 port/gw_rtos.c 用 tick 计数接）
 *
 * ⚠️ 必须在 `gw_sched_start()` **之前**调用：开始的那一刻要记下计时基准
 *    （`wd_ref_ms`），否则"从来没登记过心跳"的任务没法判断它是否已经迟到。
 *
 * 不调用 = 退回 `progress` 判据（裸机行为，保持不变）。
 */
void gw_sched_set_clock_ms(gw_sched_t *s,
                           uint32_t (*now_ms)(void *ctx), void *ctx);

/**
 * ★ 任务心跳：RTOS 下每个任务每跑完一轮就登记一次
 *
 * ⚠️ 为什么不让内核/调度器替它记：RTOS 下任务体是各自独立的循环，
 *    只有任务自己知道"我这一轮跑到了这里"。裸机下由 `note_run()` 记，
 *    两条路径**用同一套字段**，喂狗判据才能保持一致。
 */
void gw_sched_note_beat(gw_sched_t *s, gw_task_id_t id);

/**
 * 挂起 / 恢复一个任务
 *
 * 用途：安全模式下禁用可能引发崩溃的任务
 * （例如反复 HardFault 后就不要再跑 DHT22 采集了）。
 */
void gw_sched_suspend(gw_sched_t *s, gw_task_id_t id);
void gw_sched_resume(gw_sched_t *s, gw_task_id_t id);
gw_task_state_t gw_sched_state(const gw_sched_t *s, gw_task_id_t id);

/** 取任务统计 */
const gw_task_stat_t *gw_sched_stat(const gw_sched_t *s, gw_task_id_t id);

/** 取任务定义 */
const gw_task_def_t *gw_sched_def(const gw_sched_t *s, gw_task_id_t id);

/**
 * 取"最坏情况最耗时"的任务
 *
 * 与 gw_timing 里的同名概念一致：按 **max_us** 判而不是按平均。
 * 这是决定 RTOS 优先级的依据。
 */
gw_task_id_t gw_sched_worst_task(const gw_sched_t *s);

/**
 * 检查所有任务的硬超时是否都被满足
 *
 * @return 1 = 全部满足；0 = 有任务错过了硬超时
 *
 * 这是"实时性是否达标"的**唯一可信判据** ——
 * 平均耗时再好看，只要有硬超时任务miss，系统就是不达标的。
 */
int gw_sched_deadlines_met(const gw_sched_t *s);

/** 任务名 */
const char *gw_sched_task_name(gw_task_id_t id);

/** 任务状态名 */
const char *gw_sched_state_str(gw_task_state_t st);

#endif /* GW_SCHED_H */

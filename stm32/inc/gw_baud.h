/**
 * @file    gw_baud.h
 * @brief   RS485 波特率运行时切换（纯逻辑，可在 PC 上单元测试）
 *
 * ============================================================================
 *  这个模块解决的问题：**切波特率时必须等总线空闲**
 *
 *  Modbus 是"一问一答"的协议，而切波特率意味着**改变双方的通信参数**：
 *
 *      上位机发请求 ──► 本机应答 ──► 上位机发下一个请求
 *                        ▲
 *                        └── 如果在这一刻切了波特率，
 *                            应答的后半段会用新的波特率发出去，
 *                            对方收到的是**半个帧 + 一段乱码**
 *
 *  后果比"丢一帧"严重得多：对方会把乱码当成新帧的开始而错位同步，
 *  接下来**连续几帧都解析失败**。现场表现是"改了波特率之后通信就乱了"。
 *
 *  ----------------------------------------------------------------------------
 *  所以切换要满足三个条件，缺一不可
 *
 *  **① 总线不处于发送中**（`tx_busy == 0`）
 *     发送中途改 BRR 会让当前帧的后半段用新波特率发出。
 *
 *  **② 不在主站等待窗口内**（`in_wait == 0`）
 *     主站发完请求正在等响应，此时改波特率会让**响应收不到**，
 *     而且主站会把这次失败算成"从机超时"，进而把一台正常的从机标记为离线。
 *
 *  **③ 收到请求后至少等一个"静默期"**
 *     上位机可能刚发完请求、帧还没收全（3.5 字符的帧界判定还没到）。
 *     立刻切换会打断这一帧的接收。所以请求后要先等一段时间
 *     （本模块用 `GW_BAUD_QUIET_MS`，默认 50 ms —— 远大于 3.5 字符时间）。
 *
 *  ----------------------------------------------------------------------------
 *  为什么做成"请求 + 延迟应用"而不是"立刻改"
 *
 *  立刻改的实现很诱人（代码短），但它把"什么时候安全"这个判断
 *  推给了调用方 —— 而调用方（收到 Modbus 写寄存器的那一刻）
 *  **恰好是最不安全的时刻**（正在处理一帧）。
 *
 *  做成两段之后，"安全时机"的判断只有一处，且完全可测。
 * ============================================================================
 */
#ifndef GW_BAUD_H
#define GW_BAUD_H

#include <stdint.h>

/**
 * 请求后到允许切换之间的静默期（毫秒）
 *
 * 为什么是 50 ms：
 *   - 最慢的 9600bps 下，3.5 字符时间约 4 ms（一个字符约 1.04 ms）
 *   - 50 ms 远大于它，也覆盖了"上位机连续发两帧"的间隔
 *   - 又足够短，操作员感觉不到延迟
 */
#define GW_BAUD_QUIET_MS        50u

/** 支持的波特率（与 gw_devinfo 的 HREG_BAUD_* 一致） */
typedef enum {
    GW_BAUD_9600   = 0,
    GW_BAUD_19200  = 1,
    GW_BAUD_38400  = 2,
    GW_BAUD_115200 = 3
} gw_baud_code_t;

/* ==================================================================
 *  上下文
 * ================================================================== */
typedef struct {
    uint32_t current;           /* 当前**已生效**的波特率（bps） */
    uint32_t pending;           /* 待切换的波特率（0 = 无待切换） */
    uint32_t quiet_acc_ms;      /* 静默期累加器 */

    /* 统计（诊断用：现场能看出"改过几次、为什么没改成"） */
    uint32_t requests;          /* 累计请求次数 */
    uint32_t applied;           /* 累计成功切换次数 */
    uint32_t rejected;          /* 因参数非法被拒的次数 */

    uint8_t  inited;
} gw_baud_t;

/* ==================================================================
 *  接口
 * ================================================================== */

/**
 * 初始化
 *
 * @param b       上下文
 * @param initial 当前实际波特率（由移植层从 UART 外设读出来，不是猜的）
 */
int gw_baud_init(gw_baud_t *b, uint32_t initial);

/**
 * 请求切换到某个波特率
 *
 * @return 0 已受理（可能立刻生效，也可能等静默期）；
 *         1 已经是目标波特率，无需切换；
 *         <0 参数非法（不在支持列表里）
 *
 * @note 本函数**不会立刻改硬件** —— 它只登记请求。
 *       真正的切换发生在 `gw_baud_tick()` 里、且条件是安全的。
 *       传 0 表示"取消待切换的请求"。
 */
int gw_baud_request(gw_baud_t *b, uint32_t bps);

/**
 * 推进状态机（主循环每轮调用）
 *
 * @param b          上下文
 * @param elapsed_ms 距上次调用经过的毫秒
 * @param tx_busy    1 = 正在发送（或等待发送完成）
 * @param in_wait    1 = 主站正在等待响应
 * @return 1 = **本轮应该执行硬件切换**（调用方去改 UART 并调 gw_baud_commit）；
 *         0 = 不切换
 *
 * ⚠️ 返回 1 时调用方**必须**紧接着调用 `gw_baud_commit()` 告知新值，
 *    否则状态机会一直认为切换没成功、反复要求切换。
 */
int gw_baud_tick(gw_baud_t *b, uint32_t elapsed_ms,
                 int tx_busy, int in_wait);

/**
 * 告知"硬件已经切到新波特率"
 *
 * @param b   上下文
 * @param bps 实际设置成功的波特率（**以硬件回读为准**）
 *
 * ⚠️ 为什么要单独一步而不是在 tick 里直接改：
 *    改 UART 是移植层的事（要停 DMA、改 BRR、重启接收），
 *    而那是可能失败的。分开之后"请求 -> 应用 -> 确认"三步清晰，
 *    且失败时状态机不会误以为已经切换。
 */
void gw_baud_commit(gw_baud_t *b, uint32_t bps);

/** 取当前生效的波特率 */
uint32_t gw_baud_current(const gw_baud_t *b);

/** 取待切换的波特率（0 = 无） */
uint32_t gw_baud_pending(const gw_baud_t *b);

/**
 * 波特率代号 -> bps
 * @return 0 表示代号非法
 */
uint32_t gw_baud_from_code(uint16_t code);

/** 波特率是否受支持 */
int gw_baud_supported(uint32_t bps);

#endif /* GW_BAUD_H */

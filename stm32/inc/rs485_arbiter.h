/**
 * @file    rs485_arbiter.h
 * @brief   RS485 半双工总线仲裁（纯逻辑，可在 PC 上单元测试）
 *
 * ============================================================================
 *  为什么要把仲裁逻辑单独抽出来？
 *
 *  它是本项目里最"时序敏感"的决策逻辑：判断错了会让两个节点同时驱动总线，
 *  表现为**随机通信失败** —— 这种问题在现场极难定位，因为
 *  "偶尔错一帧"可以被解释成干扰、线缆、终端电阻……任何原因。
 *
 *  而仲裁本身的逻辑其实很小：一张"当前持有者 × 请求角色 -> 允许/拒绝"的
 *  决策表 + 几个计数。把它从依赖 HAL 的 rs485_port.c 里抽出来之后，
 *  决策表可以被穷举测试（所有状态组合都能覆盖），
 *  而 rs485_port.c 只剩"按决策结果操作硬件"这一件薄事情。
 *
 * ----------------------------------------------------------------------------
 *  真实冲突场景（决定了策略为什么长这样）
 *
 *  本设备在 RS485 上同时扮演两个角色：
 *    - 从站：应答上位机的读写请求 —— **有硬超时**，回晚了上位机就判它离线
 *    - 主站：主动轮询现场仪表 —— **可以等**，下一轮再试代价极小
 *
 *  场景 A：主站正在"等响应"，此时收到针对本机的请求
 *    另一台主站（或上位机超时重发）发来了请求。
 *    若不响应，上位机超时 → 判定本设备离线。
 *    正确做法：**打断等待，优先响应**，本次主站请求作废（下一轮重试）。
 *
 *  场景 B：主站准备发送时，发现从站正要响应
 *    两者都没占硬件。正确做法：**从站优先**，主站本轮放弃。
 *    理由同上：从站有硬超时，主站可以等。
 *
 *  场景 C：两个节点同时驱动总线（物理冲突）
 *    这是必须避免的：双方都会收到自己发的内容（回环），CRC 必然错。
 *    仲裁的唯一目标就是让它永不发生。
 *
 *  ----------------------------------------------------------------------------
 *  仲裁策略（唯一一张决策表，测试穷举它）
 *
 *    当前持有者      请求角色     结果
 *    ------------    ---------    ----------------------------------
 *    NONE            SLAVE        允许
 *    NONE            MASTER       允许
 *    SLAVE           SLAVE        拒绝（从站不应并发；拒绝比放行安全）
 *    SLAVE           MASTER       拒绝（从站优先）
 *    MASTER          MASTER       拒绝（主站串行）
 *    MASTER          SLAVE        允许并抢占（从站有硬超时）
 *
 *  关于 MASTER->SLAVE 的"抢占"：它**不是强行打断正在进行的发送**。
 *  s_owner == MASTER 只可能出现在"已发完请求、正在等响应"的阶段，
 *  因为发送过程本身是同步执行完的。所以抢占的实际语义是
 *  "放弃等待，改用总线发从站响应"。
 * ============================================================================
 */
#ifndef RS485_ARBITER_H
#define RS485_ARBITER_H

#include <stdint.h>

/* ---------------- 总线角色 ---------------- */
typedef enum {
    RS485_ROLE_NONE   = 0,      /* 总线空闲 */
    RS485_ROLE_SLAVE  = 1,      /* 从站身份发送（响应上位机） */
    RS485_ROLE_MASTER = 2       /* 主站身份发送（轮询仪表） */
} rs485_role_t;

/* ---------------- 申请结果 ---------------- */
typedef enum {
    RS485_ACQ_OK    = 0,        /* 拿到发送权，可以发 */
    RS485_ACQ_BUSY  = -1,       /* 总线被占用，本轮放弃 */
    RS485_ACQ_PARAM = -2        /* 角色非法 */
} rs485_acq_result_t;

/* ---------------- 仲裁统计量（现场诊断 + 实测数据来源） ---------------- */
typedef struct {
    uint32_t tx_slave;          /* 从站身份发送次数 */
    uint32_t tx_master;         /* 主站身份发送次数 */
    uint32_t master_deferred;   /* 主站因总线忙/被抢占而放弃的次数 */
    uint32_t slave_preempted;   /* 从站抢占主站等待窗口的次数 */
    uint32_t wait_entered;      /* 进入等待窗口次数 */
    uint32_t wait_preempted;    /* 等待窗口被从站打断的次数 */
} rs485_arb_stat_t;

/* ---------------- 仲裁器 ---------------- */
typedef struct {
    rs485_role_t      owner;        /* 当前持有发送权的角色 */
    uint8_t           in_wait;      /* 1 = 主站正在等响应 */
    rs485_arb_stat_t  stat;
} rs485_arb_t;

/** 初始化仲裁器（清零所有状态） */
void rs485_arb_init(rs485_arb_t *a);

/* ---------------------------------------------------------------------------
 *  ★ 仲裁原子性钩子（**弱符号**；缺陷 Z，2026-10-11）
 *
 *  ⚠️ `rs485_arb_acquire()` / `_enter_wait()` 都是"检查 -> 动作"两步，
 *     裸机下靠"同一个主循环顺序执行"保证原子，**RTOS 抢占下会破**：
 *
 *        [主站任务] 判定 owner==NONE 可以拿          <-- 在此被抢占
 *        [从站任务] 判定 owner==NONE 也可以拿 -> owner=SLAVE，开始发送
 *        [主站任务] 继续 owner=MASTER，也开始发送   ==> **总线上两个发送者**
 *
 *  ⚠️ 所以改状态的四个函数（acquire / release / enter_wait / exit_wait）
 *     内部用**临界区**把"决策 + 改状态"包住（约 1 µs）；
 *     **不**包整个收发过程 —— "从站抢占主站等待窗口"是本模块的设计语义，
 *     粗粒度互斥会连它一起锁死。
 *
 *  裸机 / 主机测试里是空实现；RTOS 由 `port/gw_rtos.c` 给强定义。
 *  少一边不会报错 —— 只会静默失去原子性，CI 有文本检查盯着。
 * ------------------------------------------------------------------------- */
void rs485_arb_guard_enter(void);
void rs485_arb_guard_exit(void);

/**
 * 尝试取得发送权
 *
 * @param a     仲裁器
 * @param role  请求角色（SLAVE / MASTER）
 * @return RS485_ACQ_OK 可以发送；RS485_ACQ_BUSY 本轮放弃；RS485_ACQ_PARAM 角色非法
 *
 * @note 拿到权之后，调用方**必须**在发送结束（从站）或收到响应/超时（主站）
 *       时调用 rs485_arb_release()，否则总线会被永久占用。
 */
rs485_acq_result_t rs485_arb_acquire(rs485_arb_t *a, rs485_role_t role);

/** 释放发送权 */
void rs485_arb_release(rs485_arb_t *a);

/**
 * 主站侧：进入"等待响应"窗口
 *
 * @return 0 = 成功进入；-1 = 当前并非主站持权（说明调用时序有误）
 *
 * 调用时机：主站成功发出请求之后、开始等待响应之前。
 */
int rs485_arb_enter_wait(rs485_arb_t *a);

/**
 * 主站侧：退出"等待响应"窗口（收到响应或超时）
 *
 * 会同时释放发送权（若当前是主站持权）。
 */
void rs485_arb_exit_wait(rs485_arb_t *a);

/** 当前是否处于等待响应窗口 */
int rs485_arb_in_wait(const rs485_arb_t *a);

/** 当前持有者 */
rs485_role_t rs485_arb_owner(const rs485_arb_t *a);

/** 取统计量 */
const rs485_arb_stat_t *rs485_arb_stats(const rs485_arb_t *a);

/** 角色转字符串（日志用） */
const char *rs485_role_str(rs485_role_t role);

#endif /* RS485_ARBITER_H */

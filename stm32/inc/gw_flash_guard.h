/**
 * @file    gw_flash_guard.h
 * @brief   Flash 访问互斥（★ RTOS 下必须有；缺陷 X）
 *
 * ============================================================================
 *  为什么需要它（2026-10-11 发现）
 * ============================================================================
 *
 *  本工程的 Flash 写入/擦除分散在**两个模块**：
 *
 *      port/gw_flash_stm32.c  参数槽、日志槽
 *      port/gw_ota_port.c      OTA 镜像与元数据
 *
 *  两边各自 `HAL_FLASH_Unlock()` ... `HAL_FLASH_Lock()`，而**全工程没有任何互斥**。
 *
 *  裸机下这不是问题：只有一个主循环，所有 Flash 操作天然串行。
 *  **RTOS 下就出事了**：
 *
 *      HOUSE 任务正在擦 OTA 槽（1.4~2.7 秒，逐页擦 + 逐页让出 CPU）
 *      从站任务同时收到一条"写保持寄存器" -> 触发参数保存 -> 也在写 Flash
 *
 *  STM32F1 的 Flash 控制器**只有一个**：擦除/编程是通过 `FLASH->CR` / `FLASH->AR`
 *  这组寄存器下命令的。两个任务交错执行会：
 *
 *      · 一方的 `HAL_FLASH_Lock()` 落在另一方 Unlock/Program 中间 -> 对方操作失败
 *      · 更糟：另一方的 `HAL_FLASHEx_Erase` 在等待 BSY 时，寄存器的页地址
 *        被**覆盖** -> **擦错页**
 *        （擦到正在运行的应用页 = 设备当场变砖；擦到参数页 = 参数丢失）
 *
 *  ============================================================================
 *  做法：互斥的获取/释放**挂在原有的解锁/上锁上**
 * ============================================================================
 *
 *  ⚠️ 关键设计：不改任何 return 路径。
 *     现成的代码里 `HAL_FLASH_Unlock()` / `(void)HAL_FLASH_Lock()` 已经**成对**
 *     出现在每条返回路径上（每个函数都仔细写过）。所以这里只是把它们换成：
 *
 *          HAL_FLASH_Unlock()        ->  gw_flash_lock()
 *          (void)HAL_FLASH_Lock();   ->  gw_flash_unlock();
 *
 *     于是"拿互斥"与"放互斥"跟着原本就正确的配对走 —— **按构造保证成对**，
 *     不需要在 7 个函数里逐个补 `goto out` 或改 return（那才是引入新 bug 的方式）。
 *
 *  ⚠️ 裸机 / 引导程序构建里是**弱符号空实现**（单线程，不需要）；RTOS 构建由
 *     `port/gw_rtos.c` 给强定义（FreeRTOS 互斥量）。
 *
 *  ⚠️ 为什么用**互斥量**而不是临界区：OTA 擦除会跨 `vTaskDelay(1)` 持有它
 *     （逐页让出 CPU）—— 临界区一旦跨阻塞调用，调度器就废了。
 * ============================================================================
 */
#ifndef GW_FLASH_GUARD_H
#define GW_FLASH_GUARD_H

#include "stm32f1xx_hal.h"

/**
 * 取互斥并解锁 Flash
 *
 * @return HAL 状态（与 `HAL_FLASH_Unlock()` 同义：失败时**已经**把互斥放掉，
 *         调用方按原来的写法 `if (gw_flash_lock() != HAL_OK) return -x;` 即可）
 */
HAL_StatusTypeDef gw_flash_lock(void);

/** 上锁 Flash 并放掉互斥 */
void gw_flash_unlock(void);

/* ---------------------------------------------------------------------------
 *  底层钩子（**弱符号**）：裸机/引导程序里是空实现，RTOS 里由 gw_rtos.c 覆盖
 *
 *  ⚠️ 与 `gw_ota_port_yield()`、`gw_rtos_housekeeping()` 同一套模式：
 *     弱定义 + 强覆盖 + CI 断言成对存在（少一边不会报错，只会静默失去保护）。
 * ------------------------------------------------------------------------- */
void gw_flash_guard_enter(void);
void gw_flash_guard_exit(void);

#endif /* GW_FLASH_GUARD_H */

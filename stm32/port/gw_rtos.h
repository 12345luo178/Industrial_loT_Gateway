/**
 * @file    gw_rtos.h
 * @brief   FreeRTOS 层：建任务、喂狗、栈水位
 *
 * ============================================================================
 *  ⚠️ 这是本项目**唯一**依赖 FreeRTOS 的文件
 *
 *  业务逻辑（src/ 与 app/）完全不认识 FreeRTOS —— 它们只提供 6 个
 *  签名为 `void (*)(void *)` 的任务入口（与 `TaskFunction_t` 一致）。
 *  本文件负责把它们挂到内核上。
 *
 *  这样划分的好处：**PC 上的 1748 项测试不需要 FreeRTOS 就能跑**。
 *  如果业务逻辑里出现一句 `vTaskDelay()`，那些测试就全废了。
 *
 *  ----------------------------------------------------------------------------
 *  迁移前后的对应关系
 *
 *      裸机（现在）                        FreeRTOS（本文件）
 *      ------------------------------      ------------------------------
 *      gw_sched_tick() 决定跑哪个任务   ->  内核按优先级抢占 + vTaskDelayUntil
 *      gw_app_poll() 一次跑完 6 个段    ->  6 个独立任务各自循环
 *      gw_timing 统计每段耗时           ->  保留（微秒级分布）
 *      主循环里喂狗（未使能）           ->  空闲任务钩子里喂（见下）
 *
 *  ----------------------------------------------------------------------------
 *  ⚠️ IWDG 喂狗为什么放在空闲任务的钩子里
 *
 *  这是整个 RTOS 化里**最关键的一个设计决定**。
 *
 *  裸机下不能开 IWDG 的原因：Flash 擦除（20~40 ms）、DHT22 时序
 *  （关中断 5 ms）都是长阻塞路径，"主循环转了一圈"并不代表
 *  "该做的事都做了"—— 主循环可以一边被长阻塞拖着、一边还在转。
 *
 *  RTOS 下不一样：
 *
 *      空闲任务只在**所有其他任务都阻塞时**才被调度
 *          ↓
 *      所以"空闲任务跑了" == "每个任务都按时阻塞了（即让出了 CPU）"
 *          ↓
 *      任一任务卡死（死循环 / 死等信号量） -> 空闲任务永远不跑
 *          ↓
 *      狗不喂 -> 复位
 *
 *  所以这条狗检测的是**任务级死锁**，而不是"CPU 还在不在取指"。
 *  后者几乎没用 —— 一个跑飞在死循环里的程序，CPU 一直在取指。
 *
 *  ----------------------------------------------------------------------------
 *  还需要额外两样东西（不在本文件，因为不属于"逻辑"）
 *
 *  1) **启动文件里把三个中断向量改名**（这是移植 FreeRTOS 最容易漏的一步）：
 *
 *         SVC_Handler      -> vPortSVCHandler
 *         PendSV_Handler   -> xPortPendSVHandler
 *         SysTick_Handler  -> xPortSysTickHandler
 *
 *     在 `startup_stm32f103xe.s` 里改，或者（更干净）在 C 里用宏：
 *
 *         #define vPortSVCHandler     SVC_Handler
 *         #define xPortPendSVHandler  PendSV_Handler
 *         #define xPortSysTickHandler SysTick_Handler
 *
 *     ⚠️ 漏了这一步的症状：程序在第一个任务切换时**直接 HardFault**。
 *
 *  2) **`HAL_InitTick()` 要把 SysTick 让给 FreeRTOS**：
 *     `HAL_Init()` 里会配 SysTick 做 HAL 的 1 ms 时基，FreeRTOS 也要用。
 *     两者共用同一个 SysTick 没有问题（FreeRTOS 的 xPortSysTickHandler
 *     里会调 HAL_IncTick），但**必须在 CubeMX 里把 HAL 时基改成别的定时器**
 *     或者确认 `HAL_InitTick` 用的是 FreeRTOS 的 tick。
 *     最省事的做法：CubeMX -> SYS -> Timebase Source 改成 TIM1（不用 SysTick）。
 * ============================================================================
 */
#ifndef GW_RTOS_H
#define GW_RTOS_H

#include <stdint.h>

#include "gw_app.h"
#include "gw_sched.h"

/* ==================================================================
 *  任务优先级
 *
 *  ⚠️ 数字越大优先级越高（FreeRTOS 约定）。
 *  划分依据来自 `gw_app_task_defs()` 里的硬超时与预算字段：
 *
 *      任务       硬超时    预算       本文件给的优先级
 *      SLAVE      5000 µs   500 µs     5（最高）
 *      MASTER     ——        200 µs     4
 *      CAN        ——        300 µs     4
 *      SENSOR     ——      10000 µs     3
 *      UPLINK     ——      20000 µs     2
 *      HOUSE      ——        200 µs     1
 *
 *  **SLAVE 最高的理由**：它是唯一有硬超时的 ——
 *  上位机发完请求就在等，超过 3.5 字符时间没响应就算超时。
 *  其他任务晚几百微秒没人察觉，从站晚一点就是通信失败。
 *
 *  ⚠️ 上板后要用 `gw_rtos_dump_stack()` 与 `gw_timing` 的数据复核：
 *     如果 HOUSE（诊断/日志）长期因为被抢占而跑不到，
 *     它的"每轮都跑"语义就失效了，日志会积压。
 * ================================================================== */
#define GW_PRIO_SLAVE       5
#define GW_PRIO_MASTER      4
#define GW_PRIO_CAN         4
#define GW_PRIO_SENSOR      3
#define GW_PRIO_UPLINK      2
#define GW_PRIO_HOUSE       1
/* UI 与 HOUSE 同级（最低）：业务任务全部更高 -> 它们一就绪就抢占 UI。 */
#define GW_PRIO_UI          1

/* ==================================================================
 *  任务栈尺寸（单位：字，Cortex-M3 上 1 字 = 4 字节）
 *
 *  ⚠️⚠️ 这些是**初值，必须上板校准**
 *
 *  这里给出的是基于调用深度的**估算**，不是实测：
 *
 *      SLAVE  384 字 = 1536 B   Modbus 从站：组帧 + RS485 发送路径
 *      MASTER 384 字 = 1536 B   主站：请求构造 + 逐从机轮询（栈最深）
 *      CAN    256 字 = 1024 B   收帧 + 通道映射写入
 *      UPLINK 512 字 = 2048 B   上云：帧解析 + 缓冲管理（路径最长）
 *      SENSOR 256 字 = 1024 B   DHT22 采样 + 滤波
 *      HOUSE  256 字 = 1024 B   日志输出 + 故障检查
 *      ------------------------------------------------
 *      合计          ≈ 8.2 KB
 *
 *  **校准方法**（上板跑 72 小时之后做，见第 7 章稳定性测试）：
 *
 *      gw_rtos_dump_stack(&app);      // 打印每个任务的剩余栈
 *
 *  然后看 `uxTaskGetStackHighWaterMark()` 的返回值（**剩余**字数的历史最小值）：
 *    - 剩余 < 20%  -> 加大（危险）
 *    - 剩余 > 60%  -> 可以减小（浪费 RAM）
 *
 *  ⚠️ 为什么要留这么多余量：栈溢出的症状是**随机 HardFault**
 *     （返回地址被覆盖），而且往往在运行几小时后才出现。
 *     先给宽、再收紧，比反过来安全得多。
 *
 *  ⚠️⚠️ **改这里的任何一个值，都要同时看 `FreeRTOSConfig.h` 的
 *     `configTOTAL_HEAP_SIZE`** —— 任务栈是从 FreeRTOS 堆里分配的，
 *     堆不够 `xTaskCreate` 就会失败、启动直接 FATAL。
 *     2026-10-11 就是这么踩的：当时堆按"6 个栈 ≈ 5.5 KB"配成 8 KB，
 *     而实际是 8.2 KB，**8 KB 连栈本身都放不下**。
 *     现在 `tools/check_rtos_hooks.py`（挂进 CI）会机械核算，改完跑 CI 即可。
 * ================================================================== */
#define GW_STACK_SLAVE      384
#define GW_STACK_MASTER     384
#define GW_STACK_CAN        256
#define GW_STACK_UPLINK     512
#define GW_STACK_SENSOR     256
#define GW_STACK_HOUSE      256
/* ⚠️ UI 的栈要给够：lcd_text 内部有一块 20 字符 x 8 像素的行缓冲（320B），
   再加 snprintf 与调用链，512 字（2KB）留了余量。
   ⚠️ 这 2KB 来自 configTOTAL_HEAP_SIZE（12KB）：加完 UI 后堆占用约
   2048(6 个业务任务) + 512(UI) + 512(空闲) + 7 个 TCB ≈ 11.1KB，
   **余量很小** —— 若上板后 xTaskCreate 报失败，先加大堆再查别的。 */
#define GW_STACK_UI         512

/* ==================================================================
 *  ★ 栈水位的自动打印间隔（秒）
 *
 *  上板后**唯一**能判断"栈给多了还是给少了"的依据就是
 *  `uxTaskGetStackHighWaterMark()`（本项目里由 `gw_rtos_dump_stack()` 打印）。
 *  ⚠️ 原来要求用户"临时加一行代码"才能看到它 —— 而"临时加代码 + 重新编译 +
 *     重新烧录"很容易被漏掉。现在由 HOUSE 任务（周期最长、开销最小）自动打：
 *
 *      GW_RTOS_DUMP_FIRST_S  —— 启动后多久打**第一次**（早点看到，便于上板当天判断）
 *      GW_RTOS_DUMP_EVERY_S  —— 之后每隔多久打一次（0 = 只打第一次）
 *
 *  ⚠️ 72 小时按每小时一次 = 72 行日志，量很小；第一次提前到 60 秒，
 *     是为了"上板当天就能看到一组水位"，不用等一小时。
 * ================================================================== */
#define GW_RTOS_DUMP_FIRST_S    60u
#define GW_RTOS_DUMP_EVERY_S    3600u

/* ==================================================================
 *  ★★ 主循环"内务"的 RTOS 侧钩子（**弱符号**；模板给强定义）
 *
 *  ⚠️⚠️ 缺陷 W（2026-10-11）：把 main 拆成"裸机主循环 / RTOS 分支"之后，
 *     **循环里剩下的内务**没人调了，而它们一个都不是可选的：
 *
 *        gw_fault_port_tick()      -> 运行时长不推进（OTA 确认要读它）
 *        gw_log_tick()             -> 日志时标停摆
 *        gw_ota_bridge_tick()      -> **OTA 传输状态机不走 -> 收不下固件**
 *        gw_ota_confirm_running()  -> **升级永不确认 -> 3 次后必然回滚**
 *        上报节拍 / 波特率切换 / 重启挂起 -> 全失效
 *
 *     一次把 RTOS 下的 OTA 与上报整条链路打死，而且**完全静默**。
 *
 *  调用方：HOUSE 任务（优先级最低、周期 10ms），每轮调一次，
 *  `dt_ms` 是**实测 tick 差**（不是标称周期 —— 被抢占延迟唤醒时不能少算时间）。
 *
 *  ⚠️ 弱定义在 `gw_rtos.c`、强定义在 `templates/main_template.c`
 *     （`#if GW_USE_FREERTOS` 里）。**两边必须成对存在**：
 *     只有弱定义 = 什么都不做（缺陷 W 悄悄回来），所以 CI 有文本检查盯着。
 * ================================================================== */
void gw_rtos_housekeeping(uint32_t dt_ms);

/**
 * ★ UI 每轮钩子（弱符号）—— 与 gw_rtos_housekeeping 同一套路：
 *   移植层不认识界面，由工程侧（main.c）覆盖成 gw_ui_tick(dt)。
 *   @param dt_ms 本轮实际经过的毫秒（用实测值，不用配置周期）
 * ⚠️ 不覆盖也能跑：弱实现是空的，UI 任务照样登记心跳、照样让出 CPU。
 */
void gw_rtos_ui_tick(uint32_t dt_ms);

/* ==================================================================
 *  IWDG
 * ================================================================== */

/** IWDG 超时（毫秒）—— 标称 3.2 s。
 *
 *  计算：LSI ≈ 40 kHz，预分频 128，重装值 1000
 *        -> 128 × 1000 / 40000 = 3.2 s
 *
 *  ⚠️ 预分频是 /128（寄存器 `IWDG_PR = 5`），不是 /64。
 *     2026-10-12 由 /64 调到 /128，目的是把窗口从 1.6 s 放宽到 3.2 s，
 *     好让 OTA 整分区擦除（1.4~2.7 s）挤得进窗口 —— 见下面的 ⚠️⚠️。
 *     ⚠️ **唯一真源在 `Core/Src/iwdg.c` 的 `IWDG_PRESCALER_REG`**（CubeMX
 *     工程侧，不在本仓库）：要改窗口只改那一行。本宏是给人读的说明，
 *     二者一旦不一致就会重演缺陷 AK（自检宏写 /64、寄存器写 /128，
 *     于是 `_Static_assert` 检查的是没人改的宏 -> 静默失效）。
 *
 *  ⚠️ LSI 的精度很差（datasheet 标称 30~60 kHz），
 *     所以实际超时在 **2.13~4.27 s** 之间。这不影响功能 ——
 *     狗的作用是"卡死时复位"，不是精确定时。
 *     ⚠️ 但**判据必须按最短窗口 2.13 s 来审**，不能按标称 3.2 s 乐观估。
 *
 *  这个值必须**大于最长的单次任务执行时间**。本项目里：
 *      - Flash 擦除一页：20~40 ms
 *      - DHT22 采样（关中断）：约 5 ms
 *      - OTA 擦除整个分区：1.4~2.7 s  ← ⚠️ 与最短窗口 2.13 s **仍然重叠**！
 *
 *  ⚠️⚠️ 所以 **OTA 升级期间必须格外处理**：
 *     擦除 136 KB（68 页 × 2 KB，分区表 v2）需要 1.4~2.7 秒，期间如果
 *     空闲任务跑不到，狗会叫。放宽到 3.2 s 只是"标称够用"，**没有消除
 *     这条风险**：LSI 跑到 60 kHz 时窗口只剩 2.13 s，仍小于 2.7 s 的最坏
 *     擦除时间。两个办法：
 *       (a) OTA 擦除放在**低优先级任务**里，每擦一页 vTaskDelay(1)
 *           让空闲任务有机会跑（推荐 —— 也更公平）
 *       (b) 擦除期间临时把 IWDG 预分频调大（不优雅，且狗已经跑着）
 *     本项目采用 (a)。如果 OTA 擦除把狗搞叫了，先检查这一点。
 */
#define GW_IWDG_TIMEOUT_MS      3200u

/* ==================================================================
 *  接口
 * ================================================================== */

/**
 * 创建全部 6 个任务（**不启动调度器**）
 *
 * @param app 应用上下文（已经 `gw_app_init()` 过）
 * @return 0 成功；<0 失败（第几个任务失败见返回值）
 *
 * 为什么分成"创建"与"启动"两步：
 *   创建任务时可能失败（堆不够）。如果把 `vTaskStartScheduler()`
 *   放在同一个函数里，失败了就没机会报告 —— 调度器一启动就不再返回，
 *   而失败的任务悄悄不存在，现场表现是"某个功能一直没有数据"。
 *   分开之后调用方可以先检查返回值、打日志、再启动。
 */
int gw_rtos_create_tasks(gw_app_t *app);

/**
 * 启动调度器（**正常情况下不返回**）
 *
 * @param app 应用上下文
 *
 * 返回说明：只有一种情况会返回 —— 堆不足，空闲任务创建失败。
 * 那时会打印错误并进入死循环（而不是返回让调用方以为一切正常）。
 */
void gw_rtos_start(gw_app_t *app);

/**
 * 使能 IWDG
 *
 * @return 0 成功
 *
 * ⚠️ 必须在 `gw_rtos_start()` **之前**调用，且只在开发完成后调用。
 *    调试阶段开着狗会很难受：断点停住超过 3.2 s（LSI 偏快时 2.13 s）就被复位。
 *    用 `gw_rtos_iwdg_enable(0)` 可以关掉（复位后失效，因为 IWDG
 *    一旦启动就无法用软件停止 —— 只能靠复位）。
 */
int gw_rtos_iwdg_enable(int enable);

/**
 * 打印每个任务的栈水位（剩余栈的最小值）
 *
 * @param app 应用上下文
 *
 * 输出格式：
 *      [STACK] SLAVE    剩余 210/384 字 (55%)
 *      [STACK] MASTER   剩余  18/384 字 ( 5%)  <-- 危险
 *
 * ⚠️ 这个函数**必须在所有任务都跑过至少一次之后**调用才有意义。
 *    `uxTaskGetStackHighWaterMark` 返回的是"历史最小剩余"，
 *    任务还没跑过时它返回的是初始值，看起来"很安全"。
 */
void gw_rtos_dump_stack(gw_app_t *app);

/**
 * 取某个任务的栈水位（剩余字数的历史最小值）
 *
 * @return 剩余字数；任务不存在或参数非法返回 0
 */
uint16_t gw_rtos_stack_free(gw_task_id_t id);

/** 取某个任务的初始栈尺寸（字） */
uint16_t gw_rtos_stack_size(gw_task_id_t id);

/**
 * 累计喂狗次数（诊断用）
 *
 * ⚠️ 这个计数**持续增长**才说明空闲任务在跑。
 *    如果它长时间不变，说明所有任务都在忙（或某个卡死了）——
 *    那时狗会叫。上板调试时盯着它能提前发现问题。
 */
uint32_t gw_rtos_feed_count(void);

/**
 * 被拒绝的喂狗次数
 *
 * 非零说明发生过"任务没按时跑完"——`gw_app_watchdog_ok()` 返回了 0。
 * **这个值应该是 0**。不是 0 就说明有任务超时了，
 * 去查 `gw_sched_stat()` 里哪个任务的 deadline_miss 增长了。
 */
uint32_t gw_rtos_feed_rejected(void);

/** 取 FreeRTOS 层用的调度器上下文（供统计查询） */
gw_sched_t *gw_rtos_sched(void);

#endif /* GW_RTOS_H */

/**
 * @file    gw_dwt.h
 * @brief   基于 DWT CYCCNT 的微秒级延时与计时（Cortex-M3 内核自带，不占外设）
 *
 * ============================================================================
 *  为什么不用别的方案？
 *
 *  | 方案              | 问题                                              |
 *  |-------------------|---------------------------------------------------|
 *  | HAL_Delay         | 毫秒级，DHT22 需要微秒级（位宽 26µs / 70µs）        |
 *  | SysTick           | 已被 HAL 时基（或 FreeRTOS）占用，改它会影响系统    |
 *  | 定时器 + 中断      | 要占用一个定时器，且中断进出有延迟抖动              |
 *  | **DWT->CYCCNT**   | **内核自带、无抖动、不占外设、精度=1 个时钟周期**   |
 *
 *  DWT（Data Watchpoint and Trace）是 Cortex-M3 内核的调试组件，
 *  其中 CYCCNT 是一个 32 位自由运行的周期计数器。72MHz 下：
 *    - 分辨率 1/72MHz ≈ 13.9 ns
 *    - 溢出周期 2^32 / 72MHz ≈ 59.6 秒（用无符号减法处理回绕即可）
 *
 *  ⚠️ 注意事项：
 *   1) 必须先使能 DWT（见 gw_dwt_init），否则 CYCCNT 恒为 0，
 *      表现为"所有延时瞬间返回、所有计时都是 0"。
 *   2) 调试器连接时 CYCCNT 会正常工作；但**不能依赖调试器**，
 *      所以初始化里显式打开，不指望 IDE 帮忙。
 *   3) 需要 Cortex-M3 的 DEMCR 寄存器 TRCENA 位。
 * ============================================================================
 */
#ifndef GW_DWT_H
#define GW_DWT_H

#include <stdint.h>

/**
 * 初始化 DWT 周期计数器
 *
 * 必须在任何 gw_dwt_us() / gw_dwt_delay_us() 调用之前执行一次。
 * 幂等：重复调用安全。
 */
void gw_dwt_init(void);

/** DWT 是否可用（初始化成功且 CYCCNT 在计数） */
int gw_dwt_is_ready(void);

/**
 * 取当前微秒时间戳（约 59.65 秒回绕一次）
 *
 * ⚠️⚠️ **不要拿两个 gw_dwt_us() 相减**。它的回绕周期是
 *      2^32 / 72 = 59,652,323 µs —— **不是 2 的幂**，
 *    所以无符号减法**没有**回绕保护：跨过回绕点会得到一个
 *    约 42.9 亿的巨大值。
 *    2026-10-14 实机症状：LVGL 标题栏耗时显示 `4235335ms`，
 *    而板子只跑了 1583 s。
 *
 *    要测"两次采样之间过了多久"，请用：
 *        uint32_t t0 = gw_dwt_cycles();
 *        ...
 *        uint32_t dt_us = gw_dwt_elapsed_us(t0);   // 回绕安全
 *
 *    本函数仍适用于"瞬时读数"（如打时间戳给日志看）。
 */
uint32_t gw_dwt_us(void);

/**
 * 取当前 CYCCNT 原始周期计数（32 位，回绕周期正好 2^32）
 *
 * 用作 gw_dwt_elapsed_us() 的基线。未就绪（DWT 不可用）时返回 0。
 */
uint32_t gw_dwt_cycles(void);

/**
 * 从 t0_cycles 到现在的微秒数（**回绕安全**）
 *
 * ⚠️ 为什么必须用这个而不是 `gw_dwt_us() - t0`：
 *    CYCCNT 是 32 位计数器，回绕周期正好 2^32，无符号减法天然正确；
 *    而 gw_dwt_us() 先除了 72，回绕周期不再是 2 的幂，减法就错了
 *    （见 gw_dwt_us() 的说明）。
 *
 *    所以正确顺序是：**先对周期数做无符号减法，再换算成微秒**。
 *
 * @param t0_cycles gw_dwt_cycles() 的返回值
 * @return 经过的微秒数。要求真实间隔 < 59.65 s；超过则回绕一次以上，值无意义。
 */
uint32_t gw_dwt_elapsed_us(uint32_t t0_cycles);

/**
 * 微秒级忙等延时
 *
 * @param us 延时微秒数。注意这是**忙等**，会占用 CPU；
 *           仅用于 DHT22 这类微秒级时序场合，不要用它做毫秒级延时。
 *
 * 实现上额外补偿了函数调用与寄存器访问的开销（见 .c 中的说明）。
 */
void gw_dwt_delay_us(uint32_t us);

#endif /* GW_DWT_H */

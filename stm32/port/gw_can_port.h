/**
 * @file    gw_can_port.h
 * @brief   bxCAN 硬件层（STM32F103 CAN1，500 kbps，接 TJA1051T/3）
 *
 * ============================================================================
 *  分层：本文件只做"硬件相关"的活
 *
 *    gw_can_core.c（纯逻辑，101 项测试）  报文映射、滤波、Bus-Off 状态机
 *    gw_can_port.c（本文件，依赖 HAL）    位时序、筛选器、收发、错误查询
 *
 *  这样"策略错了"和"寄存器配错了"可以分开排查 ——
 *  和 RS485/ESP32 两个移植层是同一个思路。
 *
 *  ----------------------------------------------------------------------------
 *  硬件配置要点
 *
 *  引脚：PB8 = CAN_RX，PB9 = CAN_TX（需开启 CAN1 重映射，见 gw_config.h）
 *  收发器：TJA1051T/3（3.3V 供电，可直接与 STM32 相连）
 *
 *  位时序（500 kbps @ APB1 = 36 MHz）：
 *     波特率 = APB1 / (Prescaler × (SYNC + BS1 + BS2))
 *
 *     Prescaler = 4，BS1 = 15 tq，BS2 = 2 tq，SJW = 1 tq
 *     总 TQ = 1 + 15 + 2 = 18
 *     36 MHz / (4 × 18) = 500 kbps ✓
 *     采样点 = (1 + 15) / 18 = 88.9%
 *
 *  ⚠️ bxCAN 的硬性范围：BS1 = 1..16，BS2 = 1..8，SJW = 1..4。
 *     本文档曾经推荐过 BS1 = 20 —— 那**超出硬件范围，CubeMX 选不出来**。
 *     详见 gw_can_port.c 里那段位时序说明。
 *
 *  ⚠️ 位时序的实现在 **`gw_can_port.c`**（`CAN_PRESCALER` 等宏），
 *     不是 CubeMX 生成的 `MX_CAN_Init()`。原因是本项目要求
 *     "协议参数与硬件解耦"，位时序属于必须能编译期校验的参数，
 *     所以用 `_Static_assert` 钉在 port 层。
 *
 *     **CubeMX 里也要配成同一组值**（否则生成的 `hcan` 初值与
 *     port 层的期望不一致，现场表现为"CAN 完全通信不了"）。
 *     CubeMX 的对应项：Prescaler=4，TimeSeg1=15，TimeSeg2=2，SJW=1。
 *
 *  ⚠️ **如果现场通信不稳定，第一件要查的就是位时序与终端电阻**，
 *     而不是改软件逻辑。CAN 的物理层问题会表现为"偶尔丢帧"，
 *     和软件 bug 的现象一模一样。
 * ============================================================================
 */
#ifndef GW_CAN_PORT_H
#define GW_CAN_PORT_H

#include <stdint.h>

#include "gw_can_core.h"

/* ---------------- 状态码 ---------------- */
typedef enum {
    CAN_PORT_OK          = 0,
    CAN_PORT_ERR_PARAM   = -1,
    CAN_PORT_ERR_HAL     = -2,      /* HAL 初始化/启动失败 */
    CAN_PORT_ERR_NO_FRAME = -3      /* 当前没有待处理报文 */
} can_port_status_t;

/* ---------------- 统计量（硬件层视角） ---------------- */
typedef struct {
    uint32_t rx_isr_frames;     /* 中断里收下的报文数 */
    uint32_t rx_ring_drops;     /* 环形缓冲满导致丢弃的报文数 */
    uint32_t tx_frames;         /* 发出的报文数（当前设计中应为 0） */
    uint32_t hal_errors;        /* HAL 报告的错误次数 */
    uint32_t bus_off_seen;      /* 观察到 Bus-Off 的次数（与核心的计数可能不同，
                                   因为检测点在硬件层） */
    uint32_t error_warn_seen;   /* 观察到错误警告的次数 */
    uint32_t reinit_calls;      /* 从 Bus-Off 恢复时重新初始化的次数 */

    /* ---- 内部回环自检（can_port_loopback_test）----
       它不是业务计数器，而是"整条 CAN 软件链还活着吗"的探针：
         runs  不涨 -> 自检根本没被调用
         fails 涨   -> 控制器 / 位时序 / 滤波器 / 接收路径有问题
       这两个数配合 rx_isr_frames 能快速区分
       "没人发帧" 与 "帧进来了但没被正确处理"。 */
    uint32_t loopback_runs;
    uint32_t loopback_fails;
} can_port_stat_t;

/* ==================================================================
 *  接口
 * ================================================================== */

/**
 * 初始化 CAN 硬件并启动
 *
 * @param filt_id    硬件筛选器 ID（标准帧 11 位）
 * @param filt_mask  硬件筛选器掩码（0 = 全通过）
 * @return CAN_PORT_OK 成功；CAN_PORT_ERR_HAL 失败
 *
 * @note 同时会把 gw_can_core 与硬件层绑定：核心的恢复回调
 *       指向本模块的 `can_port_reinit()`，所以 Bus-Off 恢复是自动的。
 *
 * @note **不做报文发送**。按方案 CAN 只收不发；
 *       这个决定的价值是"软件不可能误发报文导致现场设备动作"。
 */
can_port_status_t can_port_init(uint16_t filt_id, uint16_t filt_mask);

/**
 * 周期推进
 *
 * 做两件事：
 *   1) 把中断收下的报文取出来交给 gw_can_core 处理
 *   2) 查询 HAL 错误状态，把 Bus-Off / 错误警告通知给核心
 *
 * @param elapsed_ms 距上次调用经过的毫秒数
 *
 * @return 本次处理的报文条数（诊断用）
 */
uint16_t can_port_poll(uint32_t elapsed_ms);

/**
 * 从 Bus-Off 恢复：重新初始化控制器并重启
 *
 * @return 0 成功；非 0 失败
 *
 * @note 由 gw_can_core 的恢复状态机调用（通过回调注册）。
 *       也可以由上层主动调用（例如运维下发"重启 CAN"指令）。
 */
int can_port_reinit(void);

/**
 * 自检专用：CAN **配置是否真的写进控制器**（不依赖总线）
 *
 * @return 1 = 位时序与滤波器都如我们所要求；0 = 有出入
 *
 * ------------------------------------------------------------------
 *  ⚠️ 为什么要单独有这一问，而不是"读一下核心状态"
 *
 *  核心状态（NORMAL/ERROR_WARN）只是**软件自己的记录**：
 *  位时序没写进去、滤波器根本没激活、CAN 外设时钟没使能 ——
 *  这些情况下状态照样可能是 NORMAL，报告却是"CAN 通过"。
 *  这一问直接把控制器寄存器**回读**出来核对，是总线无关的硬证据。
 *
 *  ⚠️ 它验证的是：BTR（模式 + SJW + BS1 + BS2 + 预分频）与滤波器激活位
 *     与 gw_config.h 里的常量一致。它**不**验证收发器与接线 ——
 *     那是 can_port_bus_ready() 那一问的事。
 */
int can_port_config_ok(void);

/**
 * CAN 控制器是否真的**上了总线**（能从初始化模式退出来）
 *
 * @return 1 = MSR.INAK 已清（可以与总线同步）；0 = 仍停在初始化模式
 *
 * ------------------------------------------------------------------
 *  ⚠️ 为什么必须单独有这么一个查询（2026-10-10 实测踩到）
 *
 *  bxCAN 退出初始化模式的条件是：**总线上出现 11 个连续隐性位**（完成同步）。
 *  如果 CAN_RX 被一直拉成显性（收发器没供电 / STB 待机 / CAN_H-L 被拉低 /
 *  RXD 没接），控制器就永远出不来 —— 现象是
 *      HAL_CAN_Start() 超时返回 ERROR，MSR.INAK 一直是 1
 *  而**控制器与配置本身是好的**（can_port_config_ok() 能通过）。
 *
 *  实测补充（2026-10-10）：这种情况下连**内部回环**模式都退不出初始化模式
 *  —— 所以"用回环自测绕过总线"这条路在这块板子上行不通，
 *  要验控制器配置只能用寄存器回读（见 can_port_config_ok()）。
 *
 *  把这两个事实分开报，排查方向才不会跑偏：
 *      配置回读通过 + 本函数返回 0  -> 问题在收发器/总线（不是 MCU）
 *      配置回读失败                  -> 问题在控制器/HAL/时钟配置
 * ================================================================== */
int can_port_bus_ready(void);

/**
 * 自检/诊断用：CAN **内部回环**自收自发（**不需要第二个节点**）
 *
 * @param id   测试帧的标准帧 ID
 * @param dlc  数据长度（1..8）
 * @return CAN_PORT_OK 成功；其它 失败
 *
 * ------------------------------------------------------------------
 *  ⚠️ 它能证明什么、不能证明什么
 *
 *  能证明（这条链的**全部软件环节**）：
 *      控制器 -> 位时序(BTR) -> 滤波器 -> 发送通路
 *      -> 接收中断 -> 环形缓冲 -> can_port_poll -> 核心统计
 *  不能证明：**收发器(TJA1051)、CAN_H/CAN_L 接线、120Ω 终端** ——
 *      回环模式在控制器内部绕回，报文根本不经过引脚。
 *      那三项必须有第二个节点（本工程用 PCAN）。
 *
 * ------------------------------------------------------------------
 *  两个实现上的关键点（都是踩过才写下的）
 *
 *  1) **不自己抢 FIFO**：中断保持开启，报文走正常接收路径
 *     （ISR -> 环形缓冲 -> can_port_poll -> 核心），
 *     验证方式是"核心收帧计数 +1 且诊断环里出现了这个 ID"。
 *     如果测试自己去读 FIFO，就等于把 ISR 的作用绕过去了 ——
 *     那测的只是控制器，不是这条链。
 *
 *  2) **必须恢复现场**：临时切到回环、临时用全通滤波器，
 *     结束后要换回用户的模态/滤波器并重新 Start + 重开中断
 *     （复用 can_port_reinit()，避免"恢复代码"与"初始化代码"两处各自演化）。
 *     任何一条失败路径都必须走到恢复 —— 否则 CAN 会停在回环模式，
 *     那种"静默失能"最难查。
 *
 *  ⚠️ 历史注记（为什么早先做过一版又删掉）：PB8 悬空导致 CAN_RX 被读成
 *     显性时，**连回环模式都退不出初始化模式**（同步源仍是 CAN_RX），
 *     当时这个测试必然失败。PB8 改成输入上拉之后它才可用。
 */
can_port_status_t can_port_loopback_test(uint16_t id, uint8_t dlc);

/** 取 CAN 核心上下文（供应用层读通道数据/统计） */
gw_can_core_t *can_port_core(void);

/** 取硬件层统计量 */
const can_port_stat_t *can_port_stats(void);

/** 取 HAL 句柄（供诊断打印；正常业务不应直接用它） */
void *can_port_handle(void);

#endif /* GW_CAN_PORT_H */

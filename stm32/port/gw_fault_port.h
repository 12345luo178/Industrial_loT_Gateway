/**
 * @file    gw_fault_port.h
 * @brief   故障捕获的硬件层：.noinit 持久化 + HardFault 处理 + 安全模式
 *
 * ============================================================================
 *  三个硬件相关的职责
 *
 *    1) 把 `gw_fault_rec_t` 放进 **.noinit 段** —— 复位不清零，跨复位存活
 *    2) 实现 HardFault 处理程序 —— 抓现场、写记录、触发复位
 *    3) 判断并维持**安全模式** —— 反复崩溃时降级运行，保证还能被 OTA 修复
 *
 *  纯逻辑部分（升级策略、启动原因判定）在 `gw_fault.c`，已被 88 项测试覆盖。
 *
 *  ----------------------------------------------------------------------------
 *  什么是 .noinit 段，为什么需要它
 *
 *  正常 RAM（.data / .bss）在启动时会被启动代码初始化：
 *      .data 从 Flash 拷贝初值
 *      .bss  清零
 *  所以普通全局变量**存不住"上次怎么崩的"**。
 *
 *  `.noinit` 是链接脚本里一个特殊的段：启动代码**不会碰它**，
 *  复位后内容还在（只要没断电）。
 *
 *  ⚠️ 代价：**冷启动（上电）时它的内容是随机的**。
 *     这正是 `gw_fault.c` 里那个魔数校验存在的理由 ——
 *     不校验就会把随机值当成崩溃记录，导致设备一上电就进安全模式。
 *
 *  ----------------------------------------------------------------------------
 *  ⚠️ 关于链接脚本 —— 这里更正一个常见误解（含我自己的）
 *
 *  **通常不需要**手工往链接脚本里加 `.noinit` 段。
 *
 *  实测（GNU ld 2.42 + arm-none-eabi-gcc 13.3.1，
 *  STM32F103 风格链接脚本，512K Flash / 64K RAM）：
 *
 *      链接脚本完全不提 `.noinit` 时，ld 会把它当作 **orphan section**
 *      自动创建，并且放在 `.bss` **之外**。
 *
 *      | 写法                      | .noinit 地址 | _sbss.._ebss   | 被清零? |
 *      |---------------------------|--------------|----------------|---------|
 *      | 链接脚本不写 .noinit      | 0x2000000C   | 0x20000004..08 | 不会    |
 *      | 写 .noinit 在 .bss 之前   | 0x20000004   | 0x2000000C..10 | 不会    |
 *
 *  两种写法下 `.noinit` 都落在 `_sbss`..`_ebss` 区间**之外**，
 *  启动代码清 `.bss` 时碰不到它。
 *
 *  ⚠️ 真正会出事的是**这一种写法**：
 *     显式写 `.noinit` 但**不加 `NOLOAD`**，且把它放在 `.bss` 内部 ——
 *     那样它会被算进 `_sbss`..`_ebss`，启动时被清零。
 *     如果要显式写（为了控制地址或对齐），必须带 `NOLOAD`：
 *
 *      .noinit (NOLOAD) :      // NOLOAD：不占 Flash 镜像，启动不加载
 *      {
 *        . = ALIGN(4);
 *        *(.noinit)
 *        *(.noinit*)
 *        . = ALIGN(4);
 *      } >RAM
 *
 *  ----------------------------------------------------------------------------
 *  ⚠️⚠️ 一个**真实**的约束：`.noinit` 里不能有非零初始化器
 *
 *  ARM GCC 会直接报编译错误：
 *
 *      error: only zero initializers are allowed in section '.noinit'
 *
 *  ⚠️ **主机 gcc 不报这个错** —— 所以它只在上板/交叉编译时才暴露。
 *     语义上也说得通：`.noinit` 的定义就是"启动代码不初始化它"，
 *     写初值本来就没有意义（那个值不会被加载）。
 *
 *  所以 magic **必须在运行期填**（见 `gw_fault_boot_init()`）——
 *  这也是"必须校验 magic 才能用这块内存"的又一个理由。
 *
 *  ----------------------------------------------------------------------------
 *  ⚠️ 那怎么验证它真的生效？
 *
 *  **只能跨一次真实复位看 `boot_count`**：
 *
 *      `gw_fault_port_init()` 里的自检只验证"这块内存可写、不是只读段"，
 *      **查不出"是否被启动代码清零"** —— 那需要一次真实的复位。
 *
 *      验证方法：跑一次 -> 按复位 -> 看 `boot_count` 是否 +1。
 *      不增长就说明 `.noinit` 没生效（回到上面查链接脚本）。
 * ============================================================================
 */
#ifndef GW_FAULT_PORT_H
#define GW_FAULT_PORT_H

#include <stdint.h>

#include "gw_fault.h"

/* ---------------- 安全模式下的行为开关 ----------------
 *
 * 安全模式的目标不是"继续正常干活"，而是
 * **保证设备还能被远程修复**。所以：
 *
 *   保留：Modbus 从站（能被上位机看到、能读状态）
 *         ESP32 上云链路（能收到 OTA 指令）
 *         Flash 参数（能读回配置）
 *   禁用：DHT22 采集（单总线时序最容易受干扰）
 *         CAN 收发（外部总线，干扰源）
 *         主站轮询（会长时间占用总线）
 *
 * 换句话说：**把可能引发崩溃的东西全关掉，只留通信**。
 */
typedef struct {
    uint8_t allow_dht;          /* 1 = 允许 DHT22 采集 */
    uint8_t allow_can;          /* 1 = 允许 CAN 收发 */
    uint8_t allow_master;       /* 1 = 允许主站轮询 */
} gw_safe_mode_t;

/* ==================================================================
 *  接口
 * ================================================================== */

/**
 * 初始化故障模块（**必须在 main 的最开始调用**）
 *
 * 做三件事：
 *   1) 检查 .noinit 段是否真的生效（见下方 `*_selfcheck`）
 *   2) 调用 `gw_fault_boot_init()` 判定启动原因
 *   3) 判定是否需要进安全模式
 *
 * @return 本次启动原因
 */
gw_boot_cause_t gw_fault_port_init(void);

/**
 * 取持久化记录（供上报到寄存器 / 日志）
 * 允许在任何时刻调用
 */
const gw_fault_rec_t *gw_fault_port_record(void);

/** 取本次运行抓到的故障现场（未发生过故障时 valid = 0） */
const gw_fault_ctx_t *gw_fault_port_context(void);

/** 是否需要安全模式 */
gw_safe_reason_t gw_fault_port_safe_reason(void);

/**
 * 取安全模式下的行为开关
 *
 * 非安全模式下所有字段都是 1（全部允许）。
 */
gw_safe_mode_t gw_fault_port_safe_mode(void);

/**
 * 主动复位（会先登记"这是有意重启"）
 *
 * @param delay_ms 复位前等待的毫秒数（让串口把日志吐完）
 *
 * 用于：OTA 完成后重启、收到重启指令、安全模式下由上位机触发复位。
 */
void gw_fault_port_reset(uint32_t delay_ms);

/**
 * .noinit 段自检
 *
 * @return 0 = 正常；-1 = .noinit 可能没生效（记录会跨复位丢失）
 *
 * **怎么自检**：往记录里写一个哨兵值，然后读回来。
 * 这只能查出"这块内存是否可写"，查不出"是否被启动代码清零"——
 * 后者需要跨一次真实复位才能验证。
 * 所以本函数返回 0 **不代表** .noinit 一定生效；
 * 真正的验证方法是：跑一次、复位、看 `gw_fault_port_record()->boot_count`
 * 是否累加（上板验证清单 L7 里有这一项）。
 */
int gw_fault_port_selfcheck(void);

/**
 * 由应用层周期性调用（喂狗 + 检测"安全模式下仍崩溃"）
 *
 * @note **第一阶段不做真正的看门狗使能**，只做计数与状态维护。
 *       等 FreeRTOS 化之后再打开 IWDG，因为裸机下开狗容易
 *       在某些阻塞路径（Flash 擦除、DHT22 时序）上误复位。
 */
void gw_fault_port_tick(uint32_t elapsed_ms);

/** 累计运行秒数（用于判断"稳定运行了多久"，供安全模式退出决策） */
uint32_t gw_fault_port_uptime_s(void);

/**
 * 看门狗是否已使能
 *
 * ⚠️ 2026-10-10 起**真的去读 IWDG 寄存器**（原来硬编码返回 0）。
 *    一旦启动就无法用软件关闭，所以这里返回 1 就代表"必须一直喂"。
 */
int gw_fault_port_iwdg_enabled(void);

/**
 * 喂狗（统一入口，内部先判断 IWDG 开没开）
 *
 * ⚠️ 必须喂狗的长阻塞路径（否则会被误复位：标称 3.2s，按 LSI 60kHz 最短约 2.13s）：
 *      - 主循环每轮
 *      - Flash 擦页/写（一页 20~40ms；长擦除要逐页喂）
 *      - 上板自检里 DHT22 的上电稳定等待（一次最多 400ms × 3 次）
 *      - 任何"等总线/等对端"的忙等
 */
void gw_fault_port_iwdg_feed(void);

#endif /* GW_FAULT_PORT_H */
